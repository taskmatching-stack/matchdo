/**
 * 產品關聯鏈 PDF（無網站 UI）：主產品 + 已關聯材／配，全部圖與標籤。
 */
const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');
const sharp = require('sharp');

const KIND_ZH = { prototype: '主產品', part: '配件', material: '材料' };
const MARGIN = 48;
const COLS = 4;
const IMG_H = 88;
const LABEL_H = 16;
const ROW_GAP = 10;

function resolvePdfFontPath() {
    const candidates = [
        path.join(__dirname, '..', 'assets', 'fonts', 'NotoSansTC-Regular.otf'),
        '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc',
        '/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc'
    ];
    for (let i = 0; i < candidates.length; i++) {
        if (fs.existsSync(candidates[i])) return candidates[i];
    }
    return null;
}

function registerPdfFont(doc) {
    const fontPath = resolvePdfFontPath();
    if (!fontPath) return 'Helvetica';
    try {
        if (fontPath.endsWith('.ttc')) {
            doc.registerFont('CJK', fontPath, 'NotoSansCJK-Regular');
        } else {
            doc.registerFont('CJK', fontPath);
        }
        return 'CJK';
    } catch (e) {
        console.warn('product-link-tree-pdf: font register failed', e.message);
        return 'Helvetica';
    }
}

function isAutoGeneratedLabel(s) {
    const t = String(s || '').trim();
    if (!t || t.length < 18) return false;
    return /^[a-zA-Z0-9_.-]+$/.test(t);
}

function imageDisplayLabel(item, index, total, kind) {
    const raw = (item && item.label) ? String(item.label).trim() : '';
    if (raw && !isAutoGeneratedLabel(raw)) return raw;
    if (total <= 1) return (item && item.label) ? String(item.label).trim() : '';
    if (kind === 'prototype') return '角度 ' + String(index + 1);
    return '色款 ' + String(index + 1);
}

async function fetchImageForPdf(url) {
    const u = String(url || '').trim();
    if (!u) return null;
    try {
        const res = await fetch(u, { signal: AbortSignal.timeout(20000) });
        if (!res.ok) return null;
        const buf = Buffer.from(await res.arrayBuffer());
        return sharp(buf).rotate().jpeg({ quality: 82 }).toBuffer();
    } catch (e) {
        console.warn('product-link-tree-pdf: image fetch failed', u.slice(0, 80), e.message);
        return null;
    }
}

function safePdfFilename(title) {
    const base = String(title || 'product-link-tree').trim().replace(/[\\/:*?"<>|]/g, '_').slice(0, 60);
    return (base || 'product-link-tree') + '.pdf';
}

function ensureSpace(doc, needed) {
    if (doc.y + needed > doc.page.height - MARGIN - 24) {
        doc.addPage();
    }
}

async function drawImageGrid(doc, items, kind, font) {
    if (!items.length) {
        doc.font(font).fontSize(10).fillColor('#888888').text('（無圖片）');
        doc.moveDown(0.8);
        return;
    }
    const contentW = doc.page.width - MARGIN * 2;
    const cellW = contentW / COLS;
    const rowH = IMG_H + LABEL_H + ROW_GAP;
    let col = 0;
    let rowY = doc.y;

    for (let i = 0; i < items.length; i++) {
        if (rowY + rowH > doc.page.height - MARGIN - 20) {
            doc.addPage();
            rowY = doc.y;
            col = 0;
        }
        const x = MARGIN + col * cellW + 4;
        const y = rowY;
        const it = items[i];
        const buf = await fetchImageForPdf(it.url);
        if (buf) {
            try {
                doc.image(buf, x, y, { fit: [cellW - 8, IMG_H], align: 'center', valign: 'center' });
            } catch (_) {
                doc.rect(x, y, cellW - 8, IMG_H).stroke('#cccccc');
            }
        } else {
            doc.rect(x, y, cellW - 8, IMG_H).stroke('#cccccc');
        }
        const lab = imageDisplayLabel(it, i, items.length, kind);
        doc.font(font).fontSize(8).fillColor('#333333').text(lab, x, y + IMG_H + 3, {
            width: cellW - 8,
            align: 'center',
            lineBreak: false
        });
        col++;
        if (col >= COLS) {
            col = 0;
            rowY += rowH;
            doc.y = rowY;
        }
    }
    if (col > 0) {
        doc.y = rowY + rowH;
    }
    doc.moveDown(0.6);
}

async function drawSection(doc, asset, kind, font) {
    const kindZh = KIND_ZH[kind] || kind;
    const title = (asset && asset.title) ? String(asset.title).trim() : '';
    ensureSpace(doc, 120);
    doc.font(font).fontSize(13).fillColor('#0f766e').text(kindZh + ' · ' + (title || '未命名'));
    doc.moveDown(0.4);
    doc.fillColor('#000000');
    const items = (asset && asset.image_items) ? asset.image_items : [];
    await drawImageGrid(doc, items, kind, font);
}

/**
 * @param {{ prototype: object, linked_assets: object[] }} payload
 * @returns {Promise<Buffer>}
 */
async function generateProductLinkTreePdf(payload) {
    const proto = payload && payload.prototype;
    if (!proto) throw new Error('missing prototype');

    return new Promise(function (resolve, reject) {
        const doc = new PDFDocument({
            size: 'A4',
            margin: MARGIN,
            info: {
                Title: (proto.title || '可搭配參考') + ' - MATCHDO',
                Author: 'MATCHDO'
            }
        });
        const chunks = [];
        doc.on('data', function (c) { chunks.push(c); });
        doc.on('end', function () { resolve(Buffer.concat(chunks)); });
        doc.on('error', reject);

        (async function () {
            try {
                const font = registerPdfFont(doc);
                doc.font(font).fontSize(18).fillColor('#000000').text(
                    (proto.title || '主產品') + ' · 可搭配參考'
                );
                if (proto.manufacturer_name) {
                    doc.font(font).fontSize(11).fillColor('#555555').text('廠商：' + proto.manufacturer_name);
                }
                doc.moveDown(0.4);
                doc.font(font).fontSize(9).fillColor('#888888').text(
                    '以下為此款可搭配之材料與配件，僅供參考。'
                );
                doc.moveDown(0.8);
                doc.fillColor('#000000');

                await drawSection(doc, proto, 'prototype', font);

                const linked = payload.linked_assets || [];
                const parts = linked.filter(function (a) { return a.asset_kind === 'part'; });
                const materials = linked.filter(function (a) { return a.asset_kind === 'material'; });
                for (let i = 0; i < parts.length; i++) {
                    await drawSection(doc, parts[i], 'part', font);
                }
                for (let j = 0; j < materials.length; j++) {
                    await drawSection(doc, materials[j], 'material', font);
                }

                const dateStr = new Date().toISOString().slice(0, 10);
                doc.font(font).fontSize(8).fillColor('#999999').text(
                    'matchdo.cc · ' + dateStr,
                    MARGIN,
                    doc.page.height - MARGIN,
                    { align: 'center', width: doc.page.width - MARGIN * 2 }
                );

                doc.end();
            } catch (err) {
                doc.end();
                reject(err);
            }
        })();
    });
}

module.exports = {
    generateProductLinkTreePdf,
    safePdfFilename
};
